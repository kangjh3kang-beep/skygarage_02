import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { membershipDatabase } from './helpers/membership-database.mjs';
test('registered residences preserve site scope, independent approval, atomic recovery and member history',async()=>{
 const db=await membershipDatabase();const {pg,ids:i,call,command,as}=db;
 const directory=(actor=i.manager,site=i.siteA,building=null,after=null)=>call(actor,'platform_residence_directory',{p_site_id:site,p_building_id:building,p_after:after});
 const reason='Synthetic independent residence review';
 const createB=(actor,site,label)=>command(actor,'create_building',{site_id:site,label});
 const createU=(actor,site,building,label)=>command(actor,'create_unit',{site_id:site,building_id:building,label});
 const policy=(mode,revision=0)=>command(i.manager,'residence_policy',{site_id:i.siteA,mode,expected_revision:revision,reason});
 try{
  await assert.rejects(as(null,'select public.platform_residence_directory($1)',[i.siteA],'aal1','anon'),/permission denied/);
  await assert.rejects(call(i.hq,'platform_residence_directory',{p_site_id:i.siteA},'aal1'),/mfa_required/);
  await assert.rejects(directory(i.member),/site_access_denied/);
  await assert.rejects(directory(i.manager,i.siteB),/site_access_denied/);
  await assert.rejects(createB(i.viewer,i.siteA,'TEST'),/site_access_denied/);
  await assert.rejects(as(i.manager,'select * from platform_private.site_units'),/permission denied/);
  await assert.rejects(as(i.manager,'select platform_private.residence_change($1,$2,\'create_building\',\'{"label":"BAD"}\'::jsonb)',[i.manager,i.siteA]),/permission denied/);
  await assert.rejects(policy('registered_unit'),/active_unit_required/);
  const createKey=randomUUID(),building=await command(i.manager,'create_building',{site_id:i.siteA,label:'SYNTHETIC 101'},createKey);
  assert.equal((await command(i.manager,'create_building',{site_id:i.siteA,label:'SYNTHETIC 101'},createKey)).id,building.id);
  await assert.rejects(command(i.manager,'create_building',{site_id:i.siteA,label:'CHANGED'},createKey),/idempotency_conflict/);
  await assert.rejects(createB(i.manager,i.siteA,' SYNTHETIC 101 '),/duplicate key/);
  await assert.rejects(createB(i.manager,i.siteA,''),/invalid_residence_label/);
  const b=await createB(i.otherManager,i.siteB,'SYNTHETIC 101');
  await assert.rejects(createU(i.manager,i.siteA,b.id,'101'),/building_unavailable/);
  const unit=await createU(i.manager,i.siteA,building.id,'101');
  const otherUnit=await createU(i.otherManager,i.siteB,b.id,'101');
  await assert.rejects(pg.query('insert into platform_private.site_units(site_id,building_id,label) values($1,$2,\'BAD\')',[i.siteA,b.id]),/foreign key/);
  assert.equal((await directory(i.viewer)).can_manage,false);
  assert.equal((await directory()).rows.length,1);
  await assert.rejects(directory(i.manager,i.siteA,b.id),/building_unavailable/);
  const invitation=await command(i.manager,'issue_invite',{site_id:i.siteA,days:1,max_uses:10});
  const request=await command(i.member,'apply',{code:invitation.code,unit_label:'Untrusted claimed unit',unit_id:otherUnit.id});
  assert.equal((await pg.query('select unit_id from platform_private.membership_requests where id=$1',[request.id])).rows[0].unit_id,null,'applicants cannot self-assign the registered unit');
  await command(i.manager,'review',{site_id:i.siteA,id:request.id,decision:'approved',expected_revision:1,reason});
  await assert.rejects(directory(i.member),/site_access_denied/,'an active resident still cannot enumerate other households');
  await assert.rejects(policy('registered_unit'),/unmapped_active_members/);
  const memberRow=(await call(i.manager,'platform_membership_snapshot',{p_site_id:i.siteA,p_kind:'members'})).rows.find(r=>r.user_id===i.member);
  const link={site_id:i.siteA,user_id:i.member,unit_id:unit.id,expected_revision:memberRow.revision,reason};
  await assert.rejects(command(i.viewer,'link_member_unit',link),/site_access_denied/);
  await assert.rejects(command(i.manager,'link_member_unit',{...link,unit_id:otherUnit.id}),/unit_unavailable/);
  assert.equal((await directory()).unmapped_active_members,1);
  const linkKey=randomUUID();await command(i.manager,'link_member_unit',link,linkKey);await command(i.manager,'link_member_unit',link,linkKey);
  assert.equal((await directory()).unmapped_active_members,0);
  const own=await call(i.member,'platform_my_memberships');
  assert.equal(own.memberships[0].unit_id,unit.id);assert.equal(own.memberships[0].unit_label,'SYNTHETIC 101 101');
  await policy('registered_unit');
  await assert.rejects(policy('free_text',0),/version_conflict/);
  assert.equal((await directory()).policy.mode,'registered_unit');
  const pending=await command(i.otherMember,'apply',{code:invitation.code,unit_label:'Another untrusted unit'});
  const review={site_id:i.siteA,id:pending.id,expected_revision:1,decision:'approved',reason};
  await assert.rejects(command(i.manager,'review',review),/registered_unit_required/);
  await assert.rejects(command(i.manager,'review',{...review,unit_id:otherUnit.id}),/unit_unavailable/);
  const unchanged=(await pg.query('select status,revision,unit_id from platform_private.membership_requests where id=$1',[pending.id])).rows[0];
  assert.deepEqual(unchanged,{status:'pending',revision:1,unit_id:null});
  await command(i.manager,'review',{...review,unit_id:unit.id});
  assert.equal((await directory(i.manager,i.siteA,building.id)).rows[0].active_members,2,'multiple verified people can share a unit');
  await assert.rejects(command(i.manager,'set_unit_active',{site_id:i.siteA,id:unit.id,expected_revision:1,active:false,reason}),/unit_in_use/);
  await assert.rejects(command(i.manager,'set_building_active',{site_id:i.siteA,id:building.id,expected_revision:1,active:false,reason}),/building_has_active_units/);
  // A different site membership and every historical linkage survive the first site's revocation.
  const inviteB=await command(i.otherManager,'issue_invite',{site_id:i.siteB,days:1,max_uses:10});
  const rb=await command(i.member,'apply',{code:inviteB.code,unit_label:'SYNTHETIC B'});
  await command(i.otherManager,'review',{site_id:i.siteB,id:rb.id,expected_revision:1,decision:'approved',reason,unit_id:otherUnit.id});
  for(const who of [i.member,i.otherMember]){
   const row=(await call(i.manager,'platform_membership_snapshot',{p_site_id:i.siteA,p_kind:'members'})).rows.find(r=>r.user_id===who);
   await command(i.manager,'revoke_member',{site_id:i.siteA,user_id:who,expected_revision:row.revision,reason});
  }
  await command(i.manager,'set_unit_active',{site_id:i.siteA,id:unit.id,expected_revision:1,active:false,reason});
  await assert.rejects(command(i.manager,'set_unit_active',{site_id:i.siteA,id:unit.id,expected_revision:1,active:true,reason}),/version_conflict/);
  await command(i.manager,'set_building_active',{site_id:i.siteA,id:building.id,expected_revision:1,active:false,reason});
  await assert.rejects(command(i.manager,'set_unit_active',{site_id:i.siteA,id:unit.id,expected_revision:2,active:true,reason}),/building_unavailable/);
  await assert.rejects(createU(i.manager,i.siteA,building.id,'102'),/building_unavailable/);
  const retry=await command(i.otherMember,'apply',{code:invitation.code,unit_label:'SYNTHETIC RETURN'});
  await assert.rejects(command(i.manager,'review',{...review,id:retry.id,unit_id:unit.id}),/unit_unavailable/);
  assert.equal((await call(i.member,'platform_my_memberships')).memberships.find(m=>m.site_id===i.siteA).unit_id,unit.id);
  assert.equal((await call(i.member,'platform_my_memberships')).memberships.find(m=>m.site_id===i.siteB).status,'active');
  assert.equal((await call(i.otherMember,'platform_my_memberships')).applications.find(r=>r.id===pending.id).unit_id,unit.id);
  await command(i.manager,'set_building_active',{site_id:i.siteA,id:building.id,expected_revision:2,active:true,reason});
  await command(i.manager,'set_unit_active',{site_id:i.siteA,id:unit.id,expected_revision:2,active:true,reason});
  await command(i.manager,'review',{...review,id:retry.id,unit_id:unit.id});
  const self=await command(i.manager,'apply',{code:invitation.code,unit_label:'SYNTHETIC MANAGER'});
  await command(i.hq,'review',{...review,id:self.id,unit_id:unit.id});
  const managerMembership=(await call(i.hq,'platform_membership_snapshot',{p_site_id:i.siteA,p_kind:'members'})).rows.find(r=>r.user_id===i.manager);
  await assert.rejects(command(i.manager,'link_member_unit',{...link,user_id:i.manager,expected_revision:managerMembership.revision}),/independent_approver_required/);
  // 51+ building/household rows with actual UUID cursors, no cross-site page leakage.
  for(let n=0;n<51;n++)await createB(i.manager,i.siteA,`SYNTHETIC pagination ${n}`);
  const page1=await directory(),page2=await directory(i.manager,i.siteA,null,page1.next_cursor);
  assert.equal(page1.rows.length,50);assert.ok(page1.next_cursor);assert.equal(page2.next_cursor,null);
  assert.equal(new Set([...page1.rows,...page2.rows].map(r=>r.id)).size,52);
  for(let n=0;n<51;n++)await createU(i.manager,i.siteA,building.id,`SYNTHETIC ${n}`);
  const u1=await directory(i.manager,i.siteA,building.id),u2=await directory(i.manager,i.siteA,building.id,u1.next_cursor);
  assert.equal(u1.rows.length,50);assert.equal(new Set([...u1.rows,...u2.rows].map(r=>r.id)).size,52);
  await pg.query('update platform_private.site_staff set active=false where site_id=$1 and user_id=$2',[i.siteA,i.manager]);
  await assert.rejects(directory(),/site_access_denied/);
  await assert.rejects(command(i.manager,'link_member_unit',link,linkKey),/site_access_denied/);
  assert.equal((await pg.query("select count(*)::int n from platform_private.membership_events where action='link_member_unit' and user_id=$1",[i.member])).rows[0].n,1);
 }finally{await db.close();}
});
